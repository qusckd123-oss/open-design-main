// Generates public/data-config.js from environment variables (see .env.example) before dev/build.
// If no .env is present, or the values are empty, the dashboard defaults to the local latest.json
// fallback exactly like today - it must never break just because remote config is missing.
import { existsSync, mkdirSync, writeFileSync } from "node:fs";

if (existsSync(".env") && typeof process.loadEnvFile === "function") {
  try {
    process.loadEnvFile(".env");
  } catch (error) {
    console.warn(`[write-data-config] failed to read .env: ${error.message}`);
  }
}

const dataSource = process.env.DATA_SOURCE === "remote" ? "remote" : "local";
const remoteDataUrl = process.env.VITE_PRODUCT_DATA_URL || "";
const remoteTimeoutMs = Number(process.env.VITE_PRODUCT_DATA_TIMEOUT_MS || 8000);

const config = {
  dataSource,
  remoteDataUrl,
  remoteTimeoutMs: Number.isFinite(remoteTimeoutMs) ? remoteTimeoutMs : 8000
};

const fileContents = `// Generated by scripts/write-data-config.mjs from environment variables. Do not edit by hand -
// edit .env (see .env.example) and re-run \`npm run dev\` or \`npm run build\` instead.
window.__WACKY_DASHBOARD_CONFIG__ = ${JSON.stringify(config, null, 2)};
`;

mkdirSync("public", { recursive: true });
writeFileSync("public/data-config.js", fileContents, "utf8");

console.log(
  `[write-data-config] dataSource=${config.dataSource} remoteDataUrl=${config.remoteDataUrl ? "(set)" : "(empty)"} timeoutMs=${config.remoteTimeoutMs}`
);
